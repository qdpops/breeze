# translucent variants of Elastic colours: mapped by prefix, any alpha
PREFIX = {
    'rgba(55,190,255,': 'rgba(49,123,255,',   # accent
    'rgba(255,85,82,': 'rgba(240,68,91,',     # error
    'rgba(44,54,58,': 'rgba(10,27,57,',       # text
    'rgba(65,184,73,': 'rgba(32,178,108,',    # success
    'rgba(139,159,167,': 'rgba(131,137,159,',  # secondary text
}
COLOR = re.compile('|'.join(re.escape(k) for k in sorted(MAP, key=len, reverse=True)) + r'(?![0-9a-fA-F])'
                   + '|' + '|'.join(re.escape(k) for k in PREFIX), re.I)


def recolor(match):
    found = match.group(0).lower()
    return MAP.get(found) or PREFIX[found]


def blocks(css):
    """Yield (prelude, body) for top-level blocks, descending into @media."""
    i, n = 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            return
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            depth += {'{': 1, '}': -1}.get(css[k], 0)
            k += 1
        yield prelude, css[j + 1:k - 1]
        i = k


def convert(css):
    out = []
    for prelude, body in blocks(css):
        if prelude.startswith('@media'):
            inner = convert(body)
            if inner:
                out.append(prelude + '{' + ''.join(inner) + '}')
        elif prelude.startswith('@') or 'dark-mode' in prelude:
            continue  # font-face, keyframes; dark mode is off in this skin
        else:
            decls = [d for d in body.split(';') if ':' in d and COLOR.search(d.split(':', 1)[1])]
            if decls:
                fixed = [COLOR.sub(recolor, d) for d in decls]
                out.append(prelude + '{' + ';'.join(fixed) + '}')
    return out


if __name__ == '__main__':
    src, dst = sys.argv[1], sys.argv[2]
    rules = convert(open(src, encoding='utf-8').read())
    with open(dst, 'w', encoding='utf-8') as f:
        f.write('/* generated by tools/make_palette.py from Elastic styles.min.css: Elastic colours -> skin colours */\n')
        f.write('\n'.join(rules) + '\n')
    body = open(dst, encoding='utf-8').read().lower().split('*/', 1)[1]
    left = [c for c in list(MAP) + list(PREFIX) if re.search(re.escape(c.lower()) + r'(?![0-9a-f])', body)]
    assert not left, 'colours left unmapped: %s' % left
    print(len(rules), 'rules')
