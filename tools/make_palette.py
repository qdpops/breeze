"""Generate styles/elastic-palette.css: every Elastic rule that uses one of Elastic's colours,
re-emitted with the same selector and the skin's colour. Loaded right after Elastic's styles.min.css
(same specificity, later wins) and before breeze.css (explicit skin rules still win).

Usage: python3 make_palette.py <elastic styles.min.css> <output css>
"""
